function imageFormatForBucket(): "webp" {
  return "webp";
}

function imageBaseForBucket(bucket: "active" | "expanded"): string {
  return `/images/optimized/generated-themes/${bucket}`;
}

function buildRitualAssets(bucket: "active" | "expanded", sceneId: string): RitualAssetSet {
  const base = `${imageBaseForBucket(bucket)}/rituals/${sceneId}`;
  const sourceBase = `/images/generated-themes/${bucket}/rituals/${sceneId}`;
  const format = imageFormatForBucket();

  return {
    ritualBase: `${base}/ritual-base.${format}`,
    paperClosed: `${base}/paper-closed.${format}`,
    paperEmerging: `${base}/paper-emerging.${format}`,
    paperOpen: `${base}/paper-open.${format}`,
    fxParticles: `${base}/fx-particles.${format}`,
    fxReveal: `${base}/fx-reveal.${format}`,
    resultCorner: `${base}/result-corner.${format}`,
    sourceSheet: `${sourceBase}/source-sheet-v1.png`,
  };
}

