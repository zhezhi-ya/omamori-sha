function getRouteTextTone(sceneId: OmamoriRouteId): OmamoriRouteConfig["textTone"] {
  if (sceneId === "scarlet" || sceneId === "palace-of-earth-spirits") {
    return "mansion";
  }

  if (
    sceneId === "eientei" ||
    sceneId === "hakugyokurou" ||
    sceneId === "sanzu-river" ||
    sceneId === "misty-lake" ||
    sceneId === "nameless-hill"
  ) {
    return "moon";
  }

  return "shrine";
}

